/// The first `OpaqueRef:…` in a task result (`<value><array><data>
/// <value>OpaqueRef:…</value>…`).
pub fn first_ref(result: &str) -> Option<String> {
    let start = result.find("OpaqueRef:")?;
    let rest = &result[start..];
    let end = rest
        .find(|c: char| c == '<' || c.is_whitespace() || c == '"' || c == ',')
        .unwrap_or(rest.len());
    Some(rest[..end].to_owned()).filter(|r| r != "OpaqueRef:NULL")
}

/// The VM the import made, once the task says its objects exist
/// (`StoragePickerPage.CheckTask`/`GetVm`).
pub fn imported_vm(model: &ConnectionModel, task: &Ref<Task>) -> Option<Ref<Vm>> {
    let t = model.tasks.get(task)?;
    if t.other_config.get("object_creation").map(String::as_str) != Some("complete") {
        return None;
    }
    model
        .vms
        .iter()
        .find(|(_, v)| v.other_config.get(IMPORT_TASK).map(String::as_str) == Some(task.as_str()))
        .map(|(r, _)| r.clone())
}

/// `ImportVmAction.DefaultVMName`: a name more than one VM has gets the
/// first free " (n)".
pub fn default_vm_name(model: &ConnectionModel, name: &str) -> String {
    let count = |n: &str| model.vms.values().filter(|v| v.name_label == n).count();
    if count(name) <= 1 {
        return name.to_owned();
    }
    (1..)
        .map(|i| format!("{name} ({i})"))
        .find(|n| count(n) == 0)
        .expect("a free name")
}

/// Destroys what a failed or cancelled import left marked with `task`:
/// its VMs (with their disks) and its networks.
async fn remove_leftovers(
    shared: &Shared,
    connection: ConnectionId,
    op: OperationId,
    s: &Session,
    task: &Ref<Task>,
) {
    // Let the last events in.
    tokio::time::sleep(shared.options.task_poll_interval).await;
    let m = model(shared, connection);
    let mine = |oc: &HashMap<String, String>| {
        oc.get(IMPORT_TASK).map(String::as_str) == Some(task.as_str())
    };
    for (vm, record) in m.vms.iter().filter(|(_, v)| mine(&v.other_config)) {
        tracing::info!("removing the VM a failed import left");
        step(shared, op, OperationStep::RemovingImported);
        let disks: Vec<_> = record
            .vbds
            .iter()
            .filter_map(|b| m.vbds.get(b))
            .filter(|b| b.r#type != xapi::VbdType::Cd)
            .map(|b| b.vdi.clone())
            .filter(|v| m.vdis.contains_key(v))
            .collect();
        if let Err(e) = xapi::vm::destroy(s, vm).await {
            tracing::warn!(error = %e, "VM.destroy of the half-imported VM failed");
            continue;
        }
        for vdi in disks {
            if let Err(e) = xapi::vdi::destroy(s, &vdi).await {
                tracing::warn!(error = %e, "VDI.destroy of a half-imported disk failed");
            }
        }
    }
    for (net, record) in m.networks.iter().filter(|(_, n)| mine(&n.other_config)) {
        if record.vifs.is_empty() && record.pifs.is_empty() {
            let _ = xapi::network::destroy(s, net).await;
        }
    }
}

/// `ImportVmAction`.
#[allow(clippy::too_many_arguments)]
async fn import(
    shared: &Arc<Shared>,
    connection: ConnectionId,
    op: OperationId,
    s: &Session,
    cancel: &Arc<CancelFlag>,
    finish: tokio::sync::oneshot::Receiver<Option<ImportFinish>>,
    path: &str,
    sr: &Ref<Sr>,
    affinity: Option<&Ref<Host>>,
) -> Result<(), TaskOutcome> {
    let file = match tokio::fs::File::open(path).await {
        Ok(f) => f,
        Err(_) => {
            return Err(TaskOutcome::Failed(client_error(
                errors::IMPORT_FILE_MISSING,
                &[path],
            )));
        }
    };
    let length = tri!(file.metadata().await.map_err(xapi::Error::Io)).len();
    let m = model(shared, connection);
    // `SR.GetStorageHost`, else the coordinator.
    let host = m
        .srs
        .get(sr)
        .and_then(|r| objects::sr_home(&m, r))
        .cloned()
        .or_else(|| m.pool().map(|(_, p)| p.master.clone()))
        .unwrap_or_default();
    let (client, address) = tri!(crate::pool_run::transfer_client(
        shared,
        connection,
        &host,
        shared.options.transfer_timeout,
    ));
    let task = tri!(xapi::task::create(s, "put_import_task", &address).await);
    let file_name = Path::new(path)
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default();
    let pool_name = m
        .pool()
        .map(|(_, p)| objects::pool_name(&m, p))
        .unwrap_or_default();
    shared.update_operation(op, |o| {
        o.task = Some(task.clone());
        o.progress = Some(0.0);
        o.step = Some(OperationStep::Uploading {
            file: file_name.clone(),
            pool: pool_name.clone(),
            percent: 0,
        });
    });

    // The VM appears once the server made its objects.
    let watching = {
        let task = task.clone();
        let done = Arc::new(AtomicBool::new(false));
        let stop = done.clone();
        let interval = shared.options.task_poll_interval;
        let found = async move {
            loop {
                if stop.load(Ordering::SeqCst) {
                    return None;
                }
                if let Some(vm) = imported_vm(&model(shared, connection), &task) {
                    shared.update_operation(op, |o| o.created = Some(vm.clone()));
                    return Some(vm);
                }
                tokio::time::sleep(interval).await;
            }
        };
        (found, done)
    };

    let sent = {
        let shared = shared.clone();
        let file_name = file_name.clone();
        let pool_name = pool_name.clone();
        Arc::new(move |bytes: u64| {
            let fraction = bytes as f64 / length.max(1) as f64;
            shared.update_operation(op, |o| {
                o.progress = Some(fraction.min(1.0));
                o.step = Some(OperationStep::Uploading {
                    file: file_name.clone(),
                    pool: pool_name.clone(),
                    percent: (fraction * 100.0).floor().min(100.0) as u32,
                });
            });
        }) as Arc<dyn Fn(u64) + Send + Sync>
    };
    let cancelled = {
        let cancel = cancel.clone();
        Arc::new(move || cancel.is_set()) as Arc<dyn Fn() -> bool + Send + Sync>
    };
    let session_ref = s.session_ref().as_str().to_owned();
    let sr_ref = sr.as_str().to_owned();
    let params = [
        ("task_id", task.as_str()),
        ("session_id", session_ref.as_str()),
        ("restore", "false"),
        ("force", "false"),
        ("sr_id", sr_ref.as_str()),
    ];
    let buffer = shared.options.transfer_buffer.max(1);
    let upload = async {
        let reader: Box<dyn tokio::io::AsyncRead + Unpin + Send> =
            match shared.options.transfer_faults.short_read_after {
                Some(n) => Box::new(file.take(n)),
                None => Box::new(file),
            };
        tokio::select! {
            r = client.put_reader("import", &params, reader, length, buffer, sent, cancelled) => r,
            () = cancel.wait() => Err(xapi::Error::Cancelled),
        }
    };
    let (found, stop_watch) = watching;
    let (uploaded, early) = {
        tokio::pin!(found);
        tokio::pin!(upload);
        let mut early = None;
        let uploaded = loop {
            tokio::select! {
                r = &mut upload => break r,
                vm = &mut found, if early.is_none() => early = Some(vm),
            }
        };
        stop_watch.store(true, Ordering::SeqCst);
        (uploaded, early.flatten())
    };

    if let Err(e) = &uploaded {
        // The server notices the cut link; a task it never started would
        // wait forever.
        tracing::info!(error = %e, "the upload ended early");
        if matches!(
            xapi::task::get_status(s, &task).await,
            Ok(TaskStatusType::Pending)
        ) {
            let _ = xapi::task::cancel(s, &task).await;
        }
    }
    let (followed, result) = run_task_result(
        shared,
        op,
        s,
        async { Ok(task.clone()) },
        Span(1.0, 1.0),
        false,
    )
    .await;
    let failure = match (uploaded, followed) {
        (_, _) if cancel.is_set() => Some(TaskOutcome::Cancelled),
        (Ok(()), TaskOutcome::Succeeded) => None,
        (Ok(()), other) => Some(other),
        (Err(xapi::Error::Cancelled), _) => Some(TaskOutcome::Cancelled),
        (Err(xapi::Error::Io(e)), _) => Some(TaskOutcome::Failed(client_error(
            errors::IMPORT_FILE_ERROR,
            &[&e.to_string()],
        ))),
        (Err(_), TaskOutcome::Failed(server)) => Some(TaskOutcome::Failed(server)),
        (Err(e), _) => Some(TaskOutcome::Failed(client_error(
            errors::IMPORT_FAILED,
            &[&e.to_string()],
        ))),
    };
    if let Some(outcome) = failure {
        remove_leftovers(shared, connection, op, s, &task).await;
        shared.update_operation(op, |o| o.created = None);
        return Err(outcome);
    }

    // The imported VM: the task's result, or the one seen appearing.
    let vm = first_ref(&result).map(Ref::<Vm>::new).or(early);
    let Some(vm) = vm else {
        return Err(TaskOutcome::Failed(client_error(
            errors::IMPORT_FAILED,
            &["the server did not name the imported VM"],
        )));
    };
    shared.update_operation(op, |o| o.created = Some(vm.clone()));
    // `Connection.Resolve` in a loop: the cache has the VM.
    loop {
        if model(shared, connection).vms.contains_key(&vm) {
            break;
        }
        if cancel.is_set() {
            return Err(TaskOutcome::Cancelled);
        }
        tokio::time::sleep(shared.options.task_poll_interval).await;
    }
    let record = tri!(xapi::vm::get_record(s, &vm).await);
    let template = record.is_a_template;
    if template
        && record.is_default_template
        && record.other_config.get(IMPORT_TASK).map(String::as_str) != Some(task.as_str())
    {
        return Err(TaskOutcome::Failed(client_error(
            errors::IMPORT_TEMPLATE_EXISTS,
            &[],
        )));
    }
    step(shared, op, OperationStep::UpdatingImported { template });
    let name = tri!(xapi::vm::get_name_label(s, &vm).await);
    let name = default_vm_name(&model(shared, connection), &name);
    tri!(xapi::vm::set_name_label(s, &vm, &name).await);
    if !template && let Some(host) = affinity {
        tri!(xapi::vm::set_affinity(s, &vm, host).await);
    }

    // Wait here for the wizard to finish.
    step(
        shared,
        op,
        OperationStep::WaitingForImportWizard { template },
    );
    let finish = tokio::select! {
        f = finish => f.ok().flatten(),
        () = cancel.wait() => None,
    };
    let Some(finish) = finish else {
        return Err(TaskOutcome::Cancelled);
    };
    if let Some(wanted) = finish.vifs {
        step(
            shared,
            op,
            OperationStep::UpdatingImportNetworks { template },
        );
        tri!(update_vifs(shared, connection, s, &vm, &task, wanted).await);
    }
    step(shared, op, OperationStep::ImportComplete { template });
    if finish.start && !template {
        let suspended = model(shared, connection)
            .vms
            .get(&vm)
            .is_some_and(|v| v.power_state == VmPowerState::Suspended);
        shared.send(Command::Action {
            connection,
            request: ActionRequest::Vm {
                vm: vm.clone(),
                action: if suspended {
                    VmAction::Resume
                } else {
                    VmAction::Start
                },
            },
        });
    }
    Ok(())
}

/// `ImportVmAction`'s network update: each interface is moved to the
/// network chosen for its device (`VIF.move`), or destroyed; the others
/// are created; networks this import made and left unused are destroyed.
async fn update_vifs(
    shared: &Shared,
    connection: ConnectionId,
    s: &Session,
    vm: &Ref<Vm>,
    task: &Ref<Task>,
    mut wanted: Vec<ImportVif>,
) -> xapi::Result<()> {
    let vifs = xapi::vm::get_vifs(s, vm).await?;
    let mut networks = Vec::new();
    for vif in &vifs {
        let record = xapi::vif::get_record(s, vif).await?;
        networks.push(record.network.clone());
        if let Some(i) = wanted.iter().position(|w| w.device == record.device) {
            let w = wanted.remove(i);
            if w.network != record.network {
                xapi::vif::r#move(s, vif, &w.network).await?;
            }
            continue;
        }
        xapi::vif::destroy(s, vif).await?;
    }
    let m = model(shared, connection);
    for w in wanted {
        let mtu = m.networks.get(&w.network).map_or(1500, |n| n.mtu);
        let record = crate::provision_run::vif_record(vm, &w.network, w.device, &w.mac, mtu);
        xapi::vif::create(s, &record).await?;
    }
    for net in networks {
        let Ok(record) = xapi::network::get_record(s, &net).await else {
            continue;
        };
        if record.other_config.get(IMPORT_TASK).map(String::as_str) != Some(task.as_str()) {
            continue;
        }
        if record.vifs.is_empty()
            && record.pifs.is_empty()
            && let Err(e) = xapi::network::destroy(s, &net).await
        {
            tracing::warn!(error = %e, "removing a network the import made failed");
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn task_results_name_the_vm() {
        assert_eq!(
            first_ref("<value><array><data><value>OpaqueRef:ab-1</value></data></array></value>"),
            Some("OpaqueRef:ab-1".into())
        );
        assert_eq!(first_ref("OpaqueRef:x"), Some("OpaqueRef:x".into()));
        assert_eq!(first_ref(""), None);
        assert_eq!(first_ref("<value>OpaqueRef:NULL</value>"), None);
    }

    #[test]
    fn default_names() {
        let mut m = ConnectionModel::default();
        let mut add = |r: &str, n: &str| {
            let rec = xapi::VmRecord {
                name_label: n.to_owned(),
                ..Default::default()
            };
            m.vms.insert(Ref::new(r), Arc::new(rec));
        };
        add("a", "web");
        add("b", "db");
        add("c", "db");
        add("d", "db (1)");
        assert_eq!(default_vm_name(&m, "web"), "web");
        assert_eq!(default_vm_name(&m, "db"), "db (2)");
    }
}
