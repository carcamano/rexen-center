//! XVA export and import (F11a), call for call as the original's actions.
//!
//! * **Export** (`ExportVmAction`): a task is created (`task.create
//!   "export"`), then `GET /export?session_id=…&uuid=…&task_id=…` from the
//!   coordinator streams the archive into `<file>.tmp`, checked as it
//!   arrives ([`crate::xva::Verifier`], the original's `Export.verify`
//!   while copying); the task is followed meanwhile for its progress. With
//!   "Verify export on completion" the file is read again and checked.
//!   The temporary file becomes the export once all went well; a cancelled
//!   or failed export removes it. The errors are the original's: a header
//!   or block checksum mismatch, a full disk, a disk in use elsewhere, or
//!   "Export failed".
//! * **Import** (`ImportVmAction`): a task is created (`task.create
//!   "put_import_task"`), then `PUT /import?task_id=…&session_id=…
//!   &restore=false&force=false&sr_id=…` streams the file to the server
//!   holding the SR (`SR.GetStorageHost`, else the coordinator). Once the
//!   task marks `other_config["object_creation"] = "complete"`, the VM
//!   whose `other_config["import_task"]` names the task is the imported VM
//!   ([`crate::Operation::created`]): the wizard moves on to its network
//!   page. When the task ends, the VM gets its name (`DefaultVMName`: a
//!   name already used gets " (1)", " (2)"…) and home server, and the
//!   operation waits for the wizard ([`crate::Command::FinishImport`]):
//!   the interfaces are then moved to the chosen networks (`VIF.move`),
//!   destroyed or created, the networks the import made for this task and
//!   left unused are destroyed, and the VM is started if asked.
//!
//!   A cancelled or failed transfer leaves nothing: XAPI removes what a
//!   failed import made, and any VM it left marked with this task is
//!   destroyed with its disks here as well. Cancelling the wizard after the
//!   transfer keeps the imported VM, as the original does.
//!
//! Files are streamed both ways [`crate::BackendOptions::transfer_buffer`]
//! bytes at a time; they are never held in memory.

