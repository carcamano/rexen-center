/// How the client side of an export ended badly.
enum ExportError {
    Cancelled,
    Verify(XvaError),
    /// A local file error (`disk_full`: no space left).
    File(std::io::Error),
    /// The server or the link failed.
    Transfer(xapi::Error),
}

fn is_disk_full(e: &std::io::Error) -> bool {
    e.kind() == std::io::ErrorKind::StorageFull || e.raw_os_error() == Some(28)
}

/// The original's description of a failed export.
fn export_failure(client: ExportError, server: Option<xapi::Error>) -> TaskOutcome {
    match client {
        ExportError::Cancelled => TaskOutcome::Cancelled,
        ExportError::Verify(XvaError::BlockChecksum { .. }) => {
            TaskOutcome::Failed(client_error(errors::EXPORT_BLOCK_CHECKSUM, &[]))
        }
        ExportError::Verify(XvaError::HeaderChecksum | XvaError::Format(_)) => {
            TaskOutcome::Failed(client_error(errors::EXPORT_HEADER_CHECKSUM, &[]))
        }
        ExportError::File(e) if is_disk_full(&e) => {
            TaskOutcome::Failed(client_error(errors::EXPORT_DISK_FULL, &[]))
        }
        ExportError::File(e) => {
            TaskOutcome::Failed(client_error(errors::EXPORT_FAILED, &[&e.to_string()]))
        }
        // The stream ended early or the server refused: what the server
        // says is the reason, when it says something.
        ExportError::Verify(XvaError::Truncated) | ExportError::Transfer(_) => match server {
            Some(e) if e.is_api("VDI_IN_USE") => {
                TaskOutcome::Failed(client_error(errors::EXPORT_VDI_IN_USE, &[]))
            }
            Some(e) => TaskOutcome::Failed(e),
            None => {
                let reason = match client {
                    ExportError::Transfer(e) => e.to_string(),
                    _ => XvaError::Truncated.to_string(),
                };
                TaskOutcome::Failed(client_error(errors::EXPORT_FAILED, &[&reason]))
            }
        },
    }
}

/// Writes the download into `file` and checks it on the way.
async fn receive(
    shared: &Shared,
    op: OperationId,
    cancel: &CancelFlag,
    download: xapi::Result<xapi::http::Download>,
    file: &mut tokio::fs::File,
) -> Result<(), ExportError> {
    let mut download = download.map_err(ExportError::Transfer)?;
    let mut verifier = Verifier::default();
    let buffer = shared.options.transfer_buffer.max(1);
    let limit = shared.options.transfer_faults.disk_full_after;
    let mut received = 0i64;
    loop {
        let chunk = tokio::select! {
            c = download.chunk() => c.map_err(ExportError::Transfer)?,
            () = cancel.wait() => return Err(ExportError::Cancelled),
        };
        let Some(chunk) = chunk else { break };
        verifier.feed(&chunk).map_err(ExportError::Verify)?;
        for piece in chunk.chunks(buffer) {
            if let Some(limit) = limit
                && received as u64 + piece.len() as u64 > limit
            {
                let room = usize::try_from(limit.saturating_sub(received as u64)).unwrap_or(0);
                let _ = file.write_all(&piece[..room.min(piece.len())]).await;
                return Err(ExportError::File(std::io::Error::new(
                    std::io::ErrorKind::StorageFull,
                    "no space left on device",
                )));
            }
            file.write_all(piece).await.map_err(ExportError::File)?;
            received += piece.len() as i64;
        }
        shared.update_operation(op, |o| o.step = Some(OperationStep::Exporting { received }));
    }
    verifier.finish().map_err(ExportError::Verify)?;
    Ok(())
}

/// Reads the export back and checks it ("Verify export on completion").
async fn verify_file(
    shared: &Shared,
    op: OperationId,
    cancel: &CancelFlag,
    path: &Path,
) -> Result<(), ExportError> {
    step(shared, op, OperationStep::VerifyingExport);
    let mut file = tokio::fs::File::open(path)
        .await
        .map_err(ExportError::File)?;
    let length = file
        .metadata()
        .await
        .map_err(ExportError::File)?
        .len()
        .max(1);
    let mut verifier = Verifier::default();
    let mut buf = vec![0u8; shared.options.transfer_buffer.max(1)];
    let mut read = 0u64;
    loop {
        if cancel.is_set() {
            return Err(ExportError::Cancelled);
        }
        let n = file.read(&mut buf).await.map_err(ExportError::File)?;
        if n == 0 {
            break;
        }
        verifier.feed(&buf[..n]).map_err(ExportError::Verify)?;
        read += n as u64;
        let progress = 0.5 + 0.5 * (read as f64 / length as f64);
        shared.update_operation(op, |o| o.progress = Some(progress.min(1.0)));
    }
    verifier.finish().map_err(ExportError::Verify)?;
    Ok(())
}

/// `ExportVmAction`.
#[allow(clippy::too_many_arguments)]
async fn export(
    shared: &Shared,
    connection: ConnectionId,
    op: OperationId,
    s: &Session,
    cancel: &CancelFlag,
    vm: &Ref<Vm>,
    path: &str,
    verify: bool,
) -> Result<(), TaskOutcome> {
    let m = model(shared, connection);
    let Some(record) = m.vms.get(vm) else {
        return Err(TaskOutcome::Failed(client_error(
            "HANDLE_INVALID",
            &["VM", vm.as_str()],
        )));
    };
    let coordinator = m.pool().map(|(_, p)| p.master.clone()).unwrap_or_default();
    let (client, _) = tri!(crate::pool_run::transfer_client(
        shared,
        connection,
        &coordinator,
        shared.options.transfer_timeout,
    ));
    let task = tri!(
        xapi::task::create(
            s,
            "export",
            &format!("Exporting {} to backup file", record.name_label),
        )
        .await
    );
    shared.update_operation(op, |o| {
        o.task = Some(task.clone());
        o.step = Some(OperationStep::Exporting { received: 0 });
    });
    let tmp = format!("{path}.tmp");
    let span = if verify {
        Span(0.0, 0.5)
    } else {
        Span(0.0, 0.95)
    };
    let uuid = record.uuid.clone();
    let session_ref = s.session_ref().as_str().to_owned();
    let downloading = async {
        let mut file = match tokio::fs::File::create(&tmp).await {
            Ok(f) => f,
            Err(e) => return Err(ExportError::File(e)),
        };
        let download = client
            .get(
                "export",
                &[
                    ("session_id", session_ref.as_str()),
                    ("uuid", uuid.as_str()),
                    ("task_id", task.as_str()),
                ],
            )
            .await;
        let got = receive(shared, op, cancel, download, &mut file).await;
        // `FlushFileBuffers`.
        let flushed = async {
            file.flush().await?;
            file.sync_all().await
        }
        .await;
        drop(file);
        if got.is_err() {
            // The server learns of the failure when the link drops; a task
            // that never started would wait forever (CA-11100).
            if matches!(
                xapi::task::get_status(s, &task).await,
                Ok(TaskStatusType::Pending)
            ) {
                let _ = xapi::task::cancel(s, &task).await;
            }
        }
        got.and(flushed.map_err(ExportError::File))
    };
    let following = run_task_result(shared, op, s, async { Ok(task.clone()) }, span, false);
    let (got, (followed, _)) = tokio::join!(downloading, following);
    let got = match got {
        Ok(()) if verify => verify_file(shared, op, cancel, Path::new(&tmp)).await,
        other => other,
    };
    let failure = match (got, followed) {
        (Ok(()), TaskOutcome::Succeeded) if !cancel.is_set() => None,
        (Ok(()), TaskOutcome::Succeeded) => Some(TaskOutcome::Cancelled),
        (Ok(()), TaskOutcome::Cancelled) => Some(TaskOutcome::Cancelled),
        (Ok(()), TaskOutcome::Failed(e)) => Some(export_failure(
            ExportError::Transfer(xapi::Error::Protocol(String::new())),
            Some(e),
        )),
        (Err(_), _) if cancel.is_set() => Some(TaskOutcome::Cancelled),
        (Err(client), TaskOutcome::Failed(server)) => Some(export_failure(client, Some(server))),
        (Err(client), _) => Some(export_failure(client, None)),
    };
    if let Some(outcome) = failure {
        tracing::info!("export failed or cancelled; removing the partial file");
        let _ = tokio::fs::remove_file(&tmp).await;
        return Err(outcome);
    }
    if Path::new(path).exists() {
        let _ = tokio::fs::remove_file(path).await;
    }
    if let Err(e) = tokio::fs::rename(&tmp, path).await {
        let _ = tokio::fs::remove_file(&tmp).await;
        return Err(export_failure(ExportError::File(e), None));
    }
    Ok(())
}

