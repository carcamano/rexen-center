//! VM creation, templates, snapshots and disks: the requests, when each is
//! offered, and the facts the dialogs show (the ISO list, a VM's drives,
//! default names).
//!
//! The rules follow the original console's commands (`NewVMCommand`,
//! `CopyVMCommand`, `ConvertVMToTemplateCommand`, `DeleteVMCommand`,
//! `TakeSnapshotCommand`, `RevertToSnapshotCommand`,
//! `DeleteSnapshotCommand`, `AddVirtualDiskCommand`,
//! `AttachVirtualDiskCommand`, `DetachVirtualDiskCommand`,
//! `DeleteVirtualDiskCommand`, `MoveVirtualDiskCommand`, `CDChanger`,
//! `InstallToolsCommand`). The operations themselves run in
//! [`crate::provision_run`].

use std::collections::HashSet;
use std::sync::Arc;

use xapi::{
    Host, Network, Ref, Sr, SrRecord, Vbd, VbdOperations, VbdRecord, VbdType, Vdi, VdiRecord, Vm,
    VmOperations, VmPowerState, VmRecord,
};

use crate::model::ConnectionModel;
use crate::objects::{self, VmKind};

/// The installation media of a new VM (`Page_InstallationMedia`).
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum InstallMedia {
    /// Nothing (the template's own disks boot, or the user installs later).
    None,
    /// An ISO in the VM's DVD drive.
    Iso(Ref<Vdi>),
    /// Boot from the network (PXE): `n` first in the boot order.
    Network,
}

/// Firmware of a new HVM guest (`BootModesControl`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum BootMode {
    Bios,
    Uefi,
    UefiSecure,
}

impl BootMode {
    /// The mode a VM (or template) is set to now.
    pub fn of(vm: &VmRecord) -> BootMode {
        let uefi = vm.hvm_boot_params.get("firmware").map(String::as_str) == Some("uefi");
        let secure = vm.platform.get("secureboot").map(String::as_str) == Some("true");
        match (uefi, secure) {
            (false, _) => BootMode::Bios,
            (true, false) => BootMode::Uefi,
            (true, true) => BootMode::UefiSecure,
        }
    }
}

/// A disk of a new VM (`Page_Storage`). Disks from the template's
/// provisioning instructions (`other_config["disks"]`) are made by
/// `VM.provision`; the template's own disks come with the clone or copy;
/// the others are new.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct NewVmDisk {
    pub source: DiskSource,
    /// A system disk (`type="system"` in the provisioning XML); others are
    /// user disks.
    pub system: bool,
    pub userdevice: String,
    pub name: String,
    pub description: String,
    /// Bytes.
    pub size: i64,
    pub sr: Ref<Sr>,
    pub bootable: bool,
}

/// Where a disk of a new VM comes from.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum DiskSource {
    /// A `<disk>` of the template's provisioning XML (its `device`).
    Provision,
    /// A disk the template already has (cloned or copied with it).
    Template(Ref<Vdi>),
    /// A disk added on the Storage page.
    New,
}

/// A network interface of a new VM (`Page_Networking`).
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct NewVmVif {
    pub network: Ref<Network>,
    /// Empty: generated by the server.
    pub mac: String,
}

/// Everything the New VM wizard asks.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct NewVmSpec {
    /// The template (or snapshot, for "New VM from Snapshot").
    pub template: Ref<Vm>,
    pub name: String,
    pub description: String,
    pub media: InstallMedia,
    /// The home server; `None` lets the pool choose.
    pub affinity: Option<Ref<Host>>,
    pub vcpus_max: i64,
    pub vcpus_at_startup: i64,
    /// `platform["cores-per-socket"]`; `None` leaves the template's.
    pub cores_per_socket: Option<i64>,
    pub memory_static_max: i64,
    pub memory_dynamic_min: i64,
    pub memory_dynamic_max: i64,
    pub disks: Vec<NewVmDisk>,
    /// Copy a custom template in full to this SR instead of a fast clone
    /// (the Storage page's "Use storage-level fast disk clone" unchecked).
    pub full_copy_sr: Option<Ref<Sr>>,
    pub vifs: Vec<NewVmVif>,
    /// `None` for templates that are not HVM.
    pub boot_mode: Option<BootMode>,
    pub vtpm: bool,
    /// Start the VM once made.
    pub start: bool,
}

/// How Copy VM makes the copy (`CopyVMDialog`).
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum CopyMode {
    /// Fast clone in the same SRs (`VM.clone`).
    Clone,
    /// Full copy to an SR (`VM.copy`).
    Copy(Ref<Sr>),
}

/// A new virtual disk (`NewDiskDialog`).
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct DiskSpec {
    pub name: String,
    pub description: String,
    pub sr: Ref<Sr>,
    /// Bytes.
    pub size: i64,
}

// ---- when each operation is offered ----------------------------------------

fn allows(vm: &VmRecord, op: VmOperations) -> bool {
    vm.allowed_operations.contains(&op)
}

/// New VM from this template or snapshot (`NewVMCommand` with a template
/// selected, `NewVMFromSnapshotCommand`).
pub fn can_create_from(vm: &VmRecord) -> bool {
    match objects::vm_kind(vm) {
        VmKind::UserTemplate | VmKind::DefaultTemplate => {
            allows(vm, VmOperations::Clone) || allows(vm, VmOperations::Copy)
        }
        VmKind::Snapshot => allows(vm, VmOperations::Clone),
        _ => false,
    }
}

/// Copy VM / Copy Template (`CopyVMCommand`): the VM is halted (clone or
/// copy allowed).
pub fn can_copy(vm: &VmRecord, busy: bool) -> bool {
    !busy
        && !vm.is_a_snapshot
        && !vm.is_control_domain
        && (allows(vm, VmOperations::Clone) || allows(vm, VmOperations::Copy))
}

/// Convert to Template (`ConvertVMToTemplateCommand`).
pub fn can_make_template(vm: &VmRecord, busy: bool) -> bool {
    !busy && objects::vm_kind(vm) == VmKind::Guest && allows(vm, VmOperations::MakeIntoTemplate)
}

/// Delete VM / Delete Template (`DeleteVMCommand`): halted guests and user
/// templates that allow `destroy`.
pub fn can_delete(vm: &VmRecord, busy: bool) -> bool {
    !busy
        && matches!(objects::vm_kind(vm), VmKind::Guest | VmKind::UserTemplate)
        && allows(vm, VmOperations::Destroy)
}

/// Take Snapshot (`TakeSnapshotCommand`).
pub fn can_snapshot(vm: &VmRecord, busy: bool) -> bool {
    !busy
        && objects::vm_kind(vm) == VmKind::Guest
        && (allows(vm, VmOperations::Snapshot) || allows(vm, VmOperations::Checkpoint))
}

/// A snapshot with memory (`VM.checkpoint`) needs a running VM that allows
/// it.
pub fn can_checkpoint(vm: &VmRecord) -> bool {
    vm.power_state == VmPowerState::Running && allows(vm, VmOperations::Checkpoint)
}

/// Revert to this snapshot (`RevertToSnapshotCommand`).
pub fn can_revert(model: &ConnectionModel, snapshot: &VmRecord) -> bool {
    snapshot.is_a_snapshot
        && allows(snapshot, VmOperations::Revert)
        && model.vms.contains_key(&snapshot.snapshot_of)
}

/// Delete this snapshot (`DeleteSnapshotCommand`).
pub fn can_delete_snapshot(snapshot: &VmRecord) -> bool {
    snapshot.is_a_snapshot && allows(snapshot, VmOperations::Destroy)
}

/// The snapshots of `vm`, newest first.
pub fn snapshots<'a>(
    model: &'a ConnectionModel,
    vm: &VmRecord,
) -> Vec<(&'a Ref<Vm>, &'a Arc<VmRecord>)> {
    let mut out: Vec<_> = model
        .vms
        .iter()
        .filter(|(_, s)| {
            s.is_a_snapshot
                && vm
                    .snapshots
                    .iter()
                    .any(|r| model.vms.get(r).is_some_and(|x| Arc::ptr_eq(x, s)))
        })
        .collect();
    out.sort_by(|a, b| {
        b.1.snapshot_time
            .cmp(&a.1.snapshot_time)
            .then_with(|| a.1.name_label.cmp(&b.1.name_label))
    });
    out
}

/// A drive of a VM with its disk.
pub type VmDisk<'a> = (
    &'a Ref<Vbd>,
    &'a Arc<VbdRecord>,
    &'a Ref<Vdi>,
    &'a Arc<VdiRecord>,
);

/// The disks (not CD drives) of a VM: its VBDs with their VDIs.
pub fn vm_disks<'a>(model: &'a ConnectionModel, vm: &VmRecord) -> Vec<VmDisk<'a>> {
    let mut out: Vec<_> = vm
        .vbds
        .iter()
        .filter_map(|r| model.vbds.get_key_value(r))
        .filter(|(_, b)| b.r#type != VbdType::Cd)
        .filter_map(|(r, b)| {
            model
                .vdis
                .get_key_value(&b.vdi)
                .map(|(vr, v)| (r, b, vr, v))
        })
        .collect();
    out.sort_by(|a, b| objects::natural_cmp(&a.1.userdevice, &b.1.userdevice));
    out
}

/// Whether a drive owns its disk (`other_config["owner"]`): such disks
/// are deleted with their VM or snapshot by default.
pub fn vbd_is_owner(vbd: &VbdRecord) -> bool {
    vbd.other_config.contains_key("owner")
}

/// A snapshot with memory (taken by `VM.checkpoint`).
pub fn snapshot_has_memory(snapshot: &VmRecord) -> bool {
    snapshot.power_state == VmPowerState::Suspended
}

/// The DVD drives of a VM, by position.
pub fn cd_drives<'a>(
    model: &'a ConnectionModel,
    vm: &VmRecord,
) -> Vec<(&'a Ref<Vbd>, &'a Arc<VbdRecord>)> {
    let mut out: Vec<_> = vm
        .vbds
        .iter()
        .filter_map(|r| model.vbds.get_key_value(r))
        .filter(|(_, b)| b.r#type == VbdType::Cd)
        .collect();
    out.sort_by(|a, b| objects::natural_cmp(&a.1.userdevice, &b.1.userdevice));
    out
}

/// Whether the ISO in a DVD drive can be changed now (`CDChanger`): the
/// drive allows insert or eject, or the VM is halted.
pub fn can_change_cd(vm: &VmRecord, vbd: &VbdRecord) -> bool {
    !vm.is_a_template
        && (vbd.allowed_operations.contains(&VbdOperations::Insert)
            || vbd.allowed_operations.contains(&VbdOperations::Eject)
            || vm.power_state == VmPowerState::Halted)
}

/// One ISO the DVD drive can take, grouped under its SR.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IsoGroup {
    pub sr: Ref<Sr>,
    pub sr_name: String,
    pub isos: Vec<(Ref<Vdi>, String)>,
}

/// The ISOs a VM's DVD drive can take (`ISODropDownBox`): every VDI of an
/// ISO SR that the VM's host can see (its resident host when it runs),
/// SRs and ISOs sorted by name. The tools SR is left out, as the original
/// does for XCP-ng 8.x (Install Tools inserts that ISO); so are hidden
/// ISOs.
pub fn iso_groups(model: &ConnectionModel, vm: Option<&VmRecord>) -> Vec<IsoGroup> {
    let home = vm.and_then(|v| {
        v.resident_on
            .non_null()
            .filter(|h| model.hosts.contains_key(*h))
            .or_else(|| crate::actions::storage_host(model, v))
    });
    let mut groups: Vec<IsoGroup> = model
        .srs
        .iter()
        .filter(|(_, sr)| sr.content_type == "iso" && !objects::sr_is_detached(model, sr))
        .filter(|(_, sr)| match home {
            // An SR the VM's host cannot see is no use.
            Some(h) => {
                sr.shared
                    || sr
                        .pbds
                        .iter()
                        .filter_map(|p| model.get(p))
                        .any(|p| &p.host == h)
            }
            None => true,
        })
        .filter(|(_, sr)| objects::sr_is_shown(sr, false) && !objects::is_tools_sr(sr))
        .map(|(r, sr)| {
            let mut isos: Vec<(Ref<Vdi>, String)> = sr
                .vdis
                .iter()
                .filter_map(|v| model.vdis.get_key_value(v))
                .filter(|(_, v)| objects::vdi_is_shown(v, false) && !v.is_a_snapshot)
                .map(|(r, v)| (r.clone(), v.name_label.clone()))
                .collect();
            isos.sort_by(|a, b| objects::natural_cmp(&a.1, &b.1));
            IsoGroup {
                sr: r.clone(),
                sr_name: sr.name_label.clone(),
                isos,
            }
        })
        .filter(|g| !g.isos.is_empty())
        .collect();
    groups.sort_by(|a, b| objects::natural_cmp(&a.sr_name, &b.sr_name));
    groups
}

/// The guest tools ISO (`VDI.is_tools_iso`, or the only VDI of the tools SR).
pub fn tools_iso(model: &ConnectionModel) -> Option<&Ref<Vdi>> {
    const NAMES: &[&str] = &["xswindrivers.iso", "xs-tools.iso", "guest-tools.iso"];
    model
        .vdis
        .iter()
        .filter(|(_, v)| {
            model
                .srs
                .get(&v.sr)
                .is_some_and(|sr| sr.content_type == "iso")
        })
        .find(|(_, v)| v.is_tools_iso || NAMES.contains(&v.name_label.as_str()))
        .map(|(r, _)| r)
        .or_else(|| {
            model
                .srs
                .values()
                .find(|sr| objects::is_tools_sr(sr))
                .and_then(|sr| sr.vdis.first())
                .filter(|r| model.vdis.contains_key(*r))
        })
}

/// Install Tools (`InstallToolsCommand`): a running guest with a DVD
/// drive that can take the tools ISO.
pub fn can_install_tools(model: &ConnectionModel, vm: &VmRecord, busy: bool) -> bool {
    !busy
        && objects::vm_kind(vm) == VmKind::Guest
        && vm.power_state == VmPowerState::Running
        && tools_iso(model).is_some()
        && cd_drives(model, vm)
            .iter()
            .any(|(_, b)| can_change_cd(vm, b))
}

/// SRs a new disk can go on (`NewDiskDialog`'s SR picker): not ISO, not
/// broken, seen by the VM's host, with room for `size` bytes.
pub fn disk_srs<'a>(
    model: &'a ConnectionModel,
    vm: Option<&VmRecord>,
) -> Vec<(&'a Ref<Sr>, &'a Arc<SrRecord>)> {
    let home = vm.and_then(|v| {
        objects::vm_home(model, v).or_else(|| crate::actions::storage_host(model, v))
    });
    let mut out: Vec<_> = model
        .srs
        .iter()
        .filter(|(_, sr)| sr.content_type != "iso" && !objects::is_tools_sr(sr))
        .filter(|(_, sr)| !objects::sr_is_broken(model, sr) && !objects::sr_is_detached(model, sr))
        .filter(|(_, sr)| sr.physical_size > 0)
        .filter(|(_, sr)| match home {
            Some(h) => {
                sr.shared
                    || sr
                        .pbds
                        .iter()
                        .filter_map(|p| model.get(p))
                        .any(|p| &p.host == h)
            }
            None => true,
        })
        .collect();
    out.sort_by(|a, b| objects::natural_cmp(&a.1.name_label, &b.1.name_label));
    out
}

/// Free space of an SR, bytes (`SR.FreeSpace`).
pub fn sr_free(sr: &SrRecord) -> i64 {
    (sr.physical_size - sr.physical_utilisation).max(0)
}

/// Disks that can be attached to `vm` (`AttachDiskDialog`): VDIs of non-ISO
/// SRs the VM can see, not snapshots, not in use by another VM (unless
/// sharable), not already on this VM.
pub fn attachable_vdis<'a>(
    model: &'a ConnectionModel,
    vm_ref: &Ref<Vm>,
    vm: &VmRecord,
) -> Vec<(&'a Ref<Vdi>, &'a Arc<VdiRecord>)> {
    let srs: HashSet<&Ref<Sr>> = disk_srs(model, Some(vm))
        .into_iter()
        .map(|(r, _)| r)
        .collect();
    let mut out: Vec<_> = model
        .vdis
        .iter()
        .filter(|(_, v)| srs.contains(&v.sr) && !v.is_a_snapshot && objects::vdi_is_shown(v, false))
        .filter(|(_, v)| {
            !v.missing && matches!(v.r#type, xapi::VdiType::User | xapi::VdiType::System)
        })
        .filter(|(_, v)| {
            let users: Vec<&Arc<VbdRecord>> = v.vbds.iter().filter_map(|b| model.get(b)).collect();
            !users.iter().any(|b| &b.vm == vm_ref)
                && (v.sharable || !users.iter().any(|b| b.currently_attached))
        })
        .collect();
    out.sort_by(|a, b| objects::natural_cmp(&a.1.name_label, &b.1.name_label));
    out
}

/// Detach (`DetachVirtualDiskCommand`): the VM is halted (and the drive
/// can be destroyed), or the drive can be unplugged.
pub fn can_detach(vm: &VmRecord, vbd: &VbdRecord) -> bool {
    !vm.is_a_snapshot
        && (if vbd.currently_attached {
            vbd.allowed_operations.contains(&VbdOperations::Unplug)
        } else {
            vm.power_state != VmPowerState::Suspended
        })
}

/// Delete a disk (`DeleteVirtualDiskCommand`): no running VM uses it, and
/// the VDI allows destroy (or does not list its operations).
pub fn can_delete_disk(model: &ConnectionModel, vdi: &VdiRecord) -> bool {
    let in_use =
        vdi.vbds.iter().filter_map(|b| model.get(b)).any(|b| {
            b.currently_attached && !b.allowed_operations.contains(&VbdOperations::Unplug)
        });
    !in_use
        && !vdi.is_a_snapshot
        && (vdi.allowed_operations.is_empty()
            || vdi
                .allowed_operations
                .contains(&xapi::VdiOperations::Destroy))
}

/// Whether the disk is attached to a running VM (resized online, moved by
/// storage live migration).
pub fn vdi_attached(model: &ConnectionModel, vdi: &VdiRecord) -> bool {
    vdi.vbds
        .iter()
        .filter_map(|b| model.get(b))
        .any(|b| b.currently_attached)
}

/// The SRs a disk can move to (`MoveVirtualDiskDialog`): any other disk SR
/// its VMs can see with room for it.
pub fn move_targets<'a>(
    model: &'a ConnectionModel,
    vdi: &VdiRecord,
) -> Vec<(&'a Ref<Sr>, &'a Arc<SrRecord>)> {
    let vm = vdi
        .vbds
        .iter()
        .filter_map(|b| model.get(b))
        .find_map(|b| model.vms.get(&b.vm));
    disk_srs(model, vm.map(|v| &**v))
        .into_iter()
        .filter(|(r, sr)| **r != vdi.sr && sr_free(sr) >= vdi.virtual_size)
        .collect()
}

/// The first free disk position of a VM (`VM.get_allowed_VBD_devices` is
/// asked at run time; this is what the dialogs show).
pub fn next_userdevice(model: &ConnectionModel, vm: &VmRecord) -> String {
    let used: HashSet<String> = vm
        .vbds
        .iter()
        .filter_map(|b| model.get(b))
        .map(|b| b.userdevice.clone())
        .collect();
    (0..255)
        .map(|n| n.to_string())
        .find(|n| !used.contains(n))
        .unwrap_or_else(|| "autodetect".to_owned())
}

/// `{name} {n}` with the first `n` not taken by `taken` (`Helpers.MakeUniqueName`).
pub fn unique_name<'a>(base: &str, taken: impl IntoIterator<Item = &'a str>) -> String {
    let taken: HashSet<&str> = taken.into_iter().collect();
    if !taken.contains(base) {
        return base.to_owned();
    }
    (1..)
        .map(|n| format!("{base} ({n})"))
        .find(|n| !taken.contains(n.as_str()))
        .unwrap_or_else(|| base.to_owned())
}

/// The names of every VM, template and snapshot of the connection.
pub fn vm_names(model: &ConnectionModel) -> impl Iterator<Item = &str> {
    model.vms.values().map(|v| v.name_label.as_str())
}

/// The names of the disks of an SR.
pub fn vdi_names<'a>(
    model: &'a ConnectionModel,
    sr: &'a SrRecord,
) -> impl Iterator<Item = &'a str> {
    sr.vdis
        .iter()
        .filter_map(|v| model.get(v))
        .map(|v| v.name_label.as_str())
}

/// One `<disk>` of a template's provisioning XML (`other_config["disks"]`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ProvisionDisk {
    pub device: String,
    /// Bytes.
    pub size: i64,
    /// The SR's uuid; empty for the pool's default SR.
    pub sr: String,
    pub bootable: bool,
    /// `system` or `user`… (kept as written).
    pub kind: String,
}

fn xml_attr(tag: &str, name: &str) -> Option<String> {
    let key = format!(" {name}=\"");
    let start = tag.find(&key)? + key.len();
    let end = tag[start..].find('"')? + start;
    Some(tag[start..end].to_owned())
}

/// Parses `<provision><disk device="0" size="…" sr="…" bootable="true"
/// type="system"/>…</provision>`.
pub fn parse_provision(xml: &str) -> Vec<ProvisionDisk> {
    xml.split("<disk")
        .skip(1)
        .map(|tag| {
            let tag = format!(" {}", tag.split('>').next().unwrap_or_default());
            ProvisionDisk {
                device: xml_attr(&tag, "device").unwrap_or_else(|| "0".to_owned()),
                size: xml_attr(&tag, "size")
                    .and_then(|s| s.parse().ok())
                    .unwrap_or(0),
                sr: xml_attr(&tag, "sr").unwrap_or_default(),
                bootable: xml_attr(&tag, "bootable").as_deref() == Some("true"),
                kind: xml_attr(&tag, "type").unwrap_or_else(|| "system".to_owned()),
            }
        })
        .collect()
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('"', "&quot;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

/// Writes the provisioning XML back (`CreateVMAction` rewrites it with the
/// sizes and SRs chosen on the Storage page before `VM.provision`).
pub fn write_provision(disks: &[ProvisionDisk]) -> String {
    let mut out = String::from("<provision>");
    for d in disks {
        out.push_str(&format!(
            "<disk device=\"{}\" size=\"{}\" sr=\"{}\" bootable=\"{}\" type=\"{}\"/>",
            xml_escape(&d.device),
            d.size,
            xml_escape(&d.sr),
            d.bootable,
            xml_escape(&d.kind)
        ));
    }
    out.push_str("</provision>");
    out
}

/// A restriction of a template's `recommendations` XML (`field` or
/// `property` name → `max` or `value`).
pub fn recommendation(vm: &VmRecord, name: &str) -> Option<String> {
    for tag in vm.recommendations.split("<restriction").skip(1) {
        let tag = format!(" {}", tag.split('>').next().unwrap_or_default());
        let named = xml_attr(&tag, "field").or_else(|| xml_attr(&tag, "property"));
        if named.as_deref() == Some(name) {
            return xml_attr(&tag, "max").or_else(|| xml_attr(&tag, "value"));
        }
    }
    None
}

/// Whether a template is HVM (has a boot policy).
pub fn is_hvm(vm: &VmRecord) -> bool {
    !vm.hvm_boot_policy.is_empty()
}

/// Boot modes a template supports (its recommendations; both when unsaid).
pub fn supported_boot_modes(vm: &VmRecord) -> Vec<BootMode> {
    if !is_hvm(vm) {
        return Vec::new();
    }
    let yes = |key: &str, default: bool| {
        recommendation(vm, key).map_or(default, |v| v == "yes" || v == "true" || v == "1")
    };
    let mut modes = Vec::new();
    if yes("supports-bios", true) {
        modes.push(BootMode::Bios);
    }
    if yes("supports-uefi", false) || BootMode::of(vm) != BootMode::Bios {
        modes.push(BootMode::Uefi);
        if yes("supports-secure-boot", false) {
            modes.push(BootMode::UefiSecure);
        }
    }
    modes
}

/// The boot mode a new VM gets by default from its template: Secure Boot
/// when the template asks for it (`secureboot` `true` or `auto` on UEFI).
pub fn default_boot_mode(vm: &VmRecord) -> Option<BootMode> {
    let modes = supported_boot_modes(vm);
    if modes.is_empty() {
        return None;
    }
    let uefi = vm.hvm_boot_params.get("firmware").map(String::as_str) == Some("uefi");
    let secure = matches!(
        vm.platform.get("secureboot").map(String::as_str),
        Some("true" | "auto")
    );
    let wanted = match (uefi, secure) {
        (true, true) if modes.contains(&BootMode::UefiSecure) => BootMode::UefiSecure,
        (true, _) => BootMode::Uefi,
        _ => BootMode::Bios,
    };
    Some(if modes.contains(&wanted) {
        wanted
    } else {
        modes[0]
    })
}

/// Whether a template wants a vTPM (`platform["vtpm"]`).
pub fn template_wants_vtpm(vm: &VmRecord) -> bool {
    vm.platform.get("vtpm").map(String::as_str) == Some("true")
}

/// Whether vTPMs can be made (not restricted by the pool's licence).
pub fn vtpm_allowed(model: &ConnectionModel) -> bool {
    model.pool().is_none_or(|(_, p)| {
        p.restrictions.get("restrict_vtpm").map(String::as_str) != Some("true")
    })
}

/// The maximum vCPUs and memory a template allows (its recommendations).
pub fn template_limits(vm: &VmRecord) -> (i64, i64) {
    let vcpus = recommendation(vm, "vcpus-max")
        .and_then(|v| v.parse().ok())
        .unwrap_or(64);
    let memory = recommendation(vm, "memory-static-max")
        .and_then(|v| v.parse().ok())
        .unwrap_or(1 << 40);
    (vcpus, memory)
}

/// A disk the Delete VM dialog lists.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DeletableDisk {
    pub vdi: Ref<Vdi>,
    pub name: String,
    /// Checked by default: the VM's drive owns it.
    pub checked: bool,
}

/// What the Delete VM dialog lists (`ConfirmVMDeleteDialog`): the disks
/// only this VM uses (checked when its drive owns them; disks other VMs
/// use are never listed), and the VM's snapshots (unchecked).
pub fn deletable_items(
    model: &ConnectionModel,
    vm_ref: &Ref<Vm>,
    vm: &VmRecord,
) -> (Vec<DeletableDisk>, Vec<(Ref<Vm>, String)>) {
    let mut disks = Vec::new();
    for vbd in vm.vbds.iter().filter_map(|b| model.get(b)) {
        if vbd.r#type == VbdType::Cd {
            continue;
        }
        let Some(vdi) = model.get(&vbd.vdi) else {
            continue;
        };
        let only_this_vm = vdi
            .vbds
            .iter()
            .filter_map(|b| model.get(b))
            .all(|b| &b.vm == vm_ref);
        if only_this_vm && !disks.iter().any(|d: &DeletableDisk| d.vdi == vbd.vdi) {
            disks.push(DeletableDisk {
                vdi: vbd.vdi.clone(),
                name: objects::vdi_name(model, vdi),
                checked: vbd_is_owner(vbd),
            });
        }
    }
    let snapshots = snapshots(model, vm)
        .into_iter()
        .map(|(r, s)| (r.clone(), s.name_label.clone()))
        .collect();
    (disks, snapshots)
}

/// Whether a disk is a system disk (`VDI.type == system`, or the VM's
/// bootable disk at position 0): its detach and delete warn more.
pub fn is_system_disk(vdi: &VdiRecord, vbd: Option<&VbdRecord>) -> bool {
    vdi.r#type == xapi::VdiType::System || vbd.is_some_and(|b| b.bootable && b.userdevice == "0")
}

