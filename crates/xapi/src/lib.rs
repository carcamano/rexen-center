/// XenAPI version this client speaks (sent on login). 2.21 = XCP-ng 8.3.
pub const API_VERSION: &str = "2.21";

/// Oldest supported XAPI API version (major, minor). 2.16 = XCP-ng 8.2.
pub const MIN_API_VERSION: (i64, i64) = (2, 16);
