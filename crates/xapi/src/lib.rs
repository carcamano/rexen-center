//! XenAPI (XAPI) client.
//!
//! The crate is split in two layers:
//!
//! * **Core (hand-written, stable):** [`endpoint`], [`tls`] (trust-on-first-use
//!   certificate pinning), [`transport`] (JSON-RPC 2.0 over HTTPS to
//!   `/jsonrpc`), [`session_handle`] ([`Session`]), [`event_batch`]
//!   (`event.from` results and the `event.inject` token), [`error`], [`refs`]
//!   (typed `OpaqueRef`s), [`datetime`], the [`XapiClass`]/[`XapiObject`]
//!   traits, the lenient deserializers in [`de`], the [`params`] helpers and
//!   the [`xapi_enum!`] macro.
//! * **API surface ([`generated`], re-exported at the crate root):** every
//!   class marker, record struct and enum, and one module per class with its
//!   calls (`xapi::vm::start`, `xapi::vm::async_start`, …). It is generated by
//!   `crates/xapi-codegen` from the pinned `xenapi.json`; do not edit it.
//!
//! This crate has no UI dependency.

