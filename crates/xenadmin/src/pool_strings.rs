//! Domain Memory, Install Certificate, Back Up / Restore, the
//! confirmations and the operation titles.
//!
//! Like [`crate::i18n::Strings`], one table per language; only English
//! exists. The English texts are the original console's
//! (`XenModel/Messages.resx` and the dialogs' and pages' own resources),
//! without the `&` access keys. Templates use `{name}` placeholders filled
//! by [`crate::i18n::fill`].

