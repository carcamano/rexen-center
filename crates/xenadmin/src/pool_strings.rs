pub fn pool_strings() -> &'static PoolStrings {
    &EN
}

/// The wording of the errors [`xen_core::pool_run`] reports itself, if
/// `code` is one.
pub fn pool_error(code: &str, params: &[String]) -> Option<String> {
    use crate::i18n::fill;
    use xen_core::pool_run::errors;
    let s = pool_strings();
    let p = |i: usize| params.get(i).map(String::as_str).unwrap_or_default();
    let size = |i: usize| {
        p(i).parse::<i64>()
            .map(|b| xen_core::format::memory_size(b, true))
            .unwrap_or_default()
    };
    Some(match code {
        errors::NO_PASSWORD => s.err_no_password.to_owned(),
        errors::JOIN_LOST => fill(s.err_join_lost, &[("host", p(0))]),
        errors::WRONG_PASSWORD => s.err_wrong_password.to_owned(),
        errors::DOM0_MEMORY_TOO_LOW => fill(
            s.err_dom0_too_low,
            &[("value", &size(0)), ("min", &size(1))],
        ),
        errors::FILE_MISSING => fill(s.err_file_missing, &[("path", p(1))]),
        errors::FILE_UNREADABLE => fill(s.err_file_unreadable, &[("path", p(1))]),
        errors::HOST_UNREACHABLE => s.err_host_unreachable.to_owned(),
        errors::FILE_ERROR => fill(s.err_file, &[("error", p(0))]),
        errors::CERTIFICATE_TIMEOUT => s.err_certificate_timeout.to_owned(),
        _ => return None,
    })
}
